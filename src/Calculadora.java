/**
 * Calculadora basica para
 * operaciones con dos números entero
 */
public class Calculadora {
    /**
     * Suma dos numeros enteros
     * @param num1
     * @param num2
     * @return
     */
    public int suma (int num1, int num2){
        return num1 + num2;
    }

    /**
     * Resta dos numeros enteros
     * @param num1
     * @param num2
     * @return
     */

    public int resta (int num1, int num2) {
        return num1 - num2;
    }

    /**
     * Multiplicación de dos números enteros
     * @param num1
     * @param num2
     * @return
     */
    public int multiplicacion (int num1, int num2) {
        return num1 * num2;
    }

    /**
     * Division de dos números enteros
     * @param num1
     * @param num2
     * @return
     */
    public int division (int num1, int num2) {
        return num1 / num2;
    }

}
